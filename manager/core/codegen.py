"""Generator module to convert a TestSuite (or suite.json data) into a clean,
idiomatic, standalone PyTest script with individual async test functions per scenario.
"""

import re
from typing import Any


def sanitize_func_name(name: str) -> str:
    """Converts a scenario name or ID into a clean python function name."""
    clean = re.sub(r"[^a-zA-Z0-9_]+", "_", name.strip().lower())
    clean = clean.strip("_")
    if not clean or clean[0].isdigit():
        clean = "test_" + clean
    if not clean.startswith("test_"):
        clean = "test_" + clean
    return clean


def filter_suite_for_successful_tests(
    suite_data: dict[str, Any],
    exec_results: dict[str, Any] | None = None,
    passed_steps_override: dict[str, list[str]] | None = None,
) -> tuple[dict[str, Any], int]:
    """Filters a suite.json dictionary to include only scenarios and steps that executed and passed ('SUCCESS').

    Returns (filtered_suite_data, total_passed_steps).
    """
    passed_by_scenario: dict[str, set[str]] = {}

    if isinstance(passed_steps_override, dict) and passed_steps_override:
        for sc_id, step_ids in passed_steps_override.items():
            if isinstance(step_ids, list):
                cleaned_ids = {str(s) for s in step_ids if s}
                if cleaned_ids:
                    passed_by_scenario.setdefault(str(sc_id), set()).update(
                        cleaned_ids
                    )
    elif isinstance(exec_results, dict):
        scenarios_map = exec_results.get("scenarios") or {}
        if isinstance(scenarios_map, dict):
            for sc_id, sc_entry in scenarios_map.items():
                if not isinstance(sc_entry, dict):
                    continue
                steps_map = sc_entry.get("steps") or {}
                if isinstance(steps_map, dict):
                    passed_ids = {
                        str(st_id)
                        for st_id, status in steps_map.items()
                        if str(status).upper() == "SUCCESS"
                    }
                    if passed_ids:
                        passed_by_scenario.setdefault(str(sc_id), set()).update(
                            passed_ids
                        )

    filtered_scenarios: list[dict[str, Any]] = []
    total_passed_steps = 0

    for sc in suite_data.get("scenarios", []):
        sc_id = str(sc.get("scenario_id") or "")
        passed_set = passed_by_scenario.get(sc_id, set())
        if not passed_set:
            continue

        setup_steps = [
            dict(s)
            for s in sc.get("setup_steps", [])
            if str(s.get("step_id") or "") in passed_set
        ]
        test_steps = [
            dict(s)
            for s in sc.get("test_steps", [])
            if str(s.get("step_id") or "") in passed_set
        ]
        teardown_steps = [
            dict(s)
            for s in sc.get("teardown_steps", [])
            if str(s.get("step_id") or "") in passed_set
        ]
        kept_count = len(setup_steps) + len(test_steps) + len(teardown_steps)
        if kept_count == 0:
            continue

        if not test_steps and setup_steps:
            test_steps = setup_steps
            setup_steps = []

        sc_copy = dict(sc)
        sc_copy["setup_steps"] = setup_steps
        sc_copy["test_steps"] = test_steps
        sc_copy["teardown_steps"] = teardown_steps
        filtered_scenarios.append(sc_copy)
        total_passed_steps += kept_count

    filtered_suite = dict(suite_data)
    filtered_suite["scenarios"] = filtered_scenarios
    return filtered_suite, total_passed_steps


def generate_python_test_suite(suite_data: dict[str, Any]) -> str:
    """Generates a complete, standalone, executable PyTest file containing
    individual test functions for each scenario in the suite.
    """
    suite_id = suite_data.get("suite_id", "oas_test_suite")
    target_base_url = suite_data.get("target_base_url", "http://localhost:8080")
    scenarios = suite_data.get("scenarios", [])

    lines = [
        '"""',
        f"Auto-Generated PyTest Integration Test Suite: {suite_id}",
        "Generated by OASVerify",
        f"Target Base URL: {target_base_url}",
        '"""',
        "",
        "import asyncio",
        "import os",
        "import re",
        "from typing import Any, Dict",
        "from urllib.parse import urlparse",
        "import httpx",
        "import pytest",
        "",
        f'BASE_URL = os.environ.get("API_BASE_URL", "{target_base_url}").rstrip("/")',
        'STEP_DELAY_SECONDS = float(os.environ.get("OAS_STEP_DELAY_SECONDS", "0.25"))',
        "",
        "",
        "# ===========================================================================",
        "# Pure-Python Runtime Helpers (Zero External Test Dependencies)",
        "# ===========================================================================",
        "def are_values_equivalent(val1: Any, val2: Any) -> bool:",
        "    if val1 == val2:",
        "        return True",
        "    if val1 is None or val2 is None:",
        "        return False",
        "    s1 = str(val1).strip().lower()",
        "    s2 = str(val2).strip().lower()",
        "    if s1 == s2:",
        "        return True",
        "    try:",
        "        if float(val1) == float(val2):",
        "            return True",
        "    except (ValueError, TypeError):",
        "        pass",
        "    return False",
        "",
        "",
        "def extract_jsonpath(payload: Any, path_expression: str) -> Any:",
        '    """Extracts values from JSON responses supporting dot/bracket notations and OpenAPI collection unwraps."""',
        "    if not isinstance(payload, (dict, list)) or not path_expression:",
        "        return None",
        "    expr = path_expression.strip()",
        '    if expr.startswith("$."):',
        "        expr = expr[2:]",
        '    elif expr.startswith("$"):',
        "        expr = expr[1:]",
        r'    tokens = re.findall(r"([^.\[\]]+)|\[(\d+)\]", expr)',
        "    curr = payload",
        "    for pos, (token, idx) in enumerate(tokens):",
        "        next_is_index = (pos + 1 < len(tokens)) and bool(tokens[pos + 1][1])",
        "        if token:",
        "            token = token.strip('\"\\'')",
        "            if isinstance(curr, dict) and token in curr:",
        "                curr = curr[token]",
        '            elif isinstance(curr, dict) and token == "@graph" and "features" in curr:',
        '                curr = curr["features"]',
        '            elif isinstance(curr, dict) and token == "features" and "@graph" in curr:',
        '                curr = curr["@graph"]',
        '            elif isinstance(curr, dict) and token == "@graph" and ("id" in curr or "@id" in curr or "type" in curr or "properties" in curr):',
        "                curr = [curr]",
        '            elif isinstance(curr, dict) and "properties" in curr and isinstance(curr["properties"], dict) and token in curr["properties"]:',
        '                curr = curr["properties"][token]',
        '            elif isinstance(curr, dict) and token in ["@id", "id"] and ("@id" in curr or "id" in curr):',
        '                curr = curr.get("@id") or curr.get("id")',
        '            elif isinstance(curr, str) and token in ["@id", "id"]:',
        "                pass",
        '            elif isinstance(curr, dict) and (token in ["entry", "items", "data", "@graph", "features", "results", "records", "locations"] or next_is_index):',
        "                matched = False",
        '                for alt in ["features", "@graph", "items", "entry", "data", "results", "records", "locations"]:',
        "                    if alt in curr and isinstance(curr[alt], (list, dict)):",
        "                        curr = curr[alt]",
        "                        matched = True",
        "                        break",
        "                if not matched and next_is_index:",
        "                    list_vals = [v for v in curr.values() if isinstance(v, list)]",
        "                    if len(list_vals) == 1:",
        "                        curr = list_vals[0]",
        "                        matched = True",
        "                    else:",
        '                        dict_vals = [v for k, v in curr.items() if not str(k).startswith("@") and isinstance(v, dict)]',
        "                        if len(dict_vals) == 1:",
        "                            curr = dict_vals[0]",
        "                            matched = True",
        "                if not matched:",
        "                    return None",
        '            elif isinstance(curr, list) and (token in ["entry", "items", "data", "@graph", "features", "results", "records", "locations"] or next_is_index):',
        "                pass",
        "            else:",
        "                return None",
        '            if token in ["@id", "id"] and isinstance(curr, str) and "/" in curr:',
        '                curr = curr.rstrip("/").split("/")[-1]',
        "        elif idx:",
        "            try:",
        "                i = int(idx)",
        "                if isinstance(curr, dict):",
        '                    for col in ["@graph", "features", "items", "data", "results", "records", "entry", "locations"]:',
        "                        if col in curr and isinstance(curr[col], list):",
        "                            curr = curr[col]",
        "                            break",
        "                if isinstance(curr, list) and 0 <= i < len(curr):",
        "                    curr = curr[i]",
        "                elif isinstance(curr, dict) and 0 <= i < len(curr):",
        '                    non_meta = [(k, v) for k, v in curr.items() if not str(k).startswith("@")]',
        "                    if 0 <= i < len(non_meta):",
        "                        k_i, v_i = non_meta[i]",
        "                        curr = v_i if isinstance(v_i, (dict, list)) else k_i",
        "                    else:",
        "                        curr = list(curr.values())[i]",
        "                else:",
        "                    return None",
        "            except (ValueError, IndexError):",
        "                return None",
        "    return curr",
        "",
        "",
        "def resolve_variables(template: str, context: Dict[str, Any]) -> str:",
        '    """Resolves {{var}} or $var syntax against captured context values."""',
        "    if not isinstance(template, str):",
        "        return template",
        r'    pattern = re.compile(r"\{\{?([a-zA-Z0-9_]+)\}?\}|\$([a-zA-Z0-9_]+)")',
        "",
        "    def replace(match):",
        "        k = match.group(1) or match.group(2)",
        "        if k in context:",
        "            return str(context[k])",
        "        return '1' if 'id' in k.lower() else f'sample_{k}'",
        "",
        "    return pattern.sub(replace, template)",
        "",
        "",
        "def resolve_deep(data: Any, context: Dict[str, Any]) -> Any:",
        "    if isinstance(data, str):",
        "        return resolve_variables(data, context)",
        "    elif isinstance(data, dict):",
        "        return {k: resolve_deep(v, context) for k, v in data.items()}",
        "    elif isinstance(data, list):",
        "        return [resolve_deep(item, context) for item in data]",
        "    return data",
    ]

    used_func_names: set[str] = set()

    for idx, sc in enumerate(scenarios):
        sc_id = sc.get("scenario_id", f"SC_{idx + 1}")
        sc_name = sc.get("name", sc_id)
        sc_desc = sc.get("description", "")
        all_steps = (
            sc.get("setup_steps", [])
            + sc.get("test_steps", [])
            + sc.get("teardown_steps", [])
        )

        raw_func_name = sanitize_func_name(f"{sc_id}_{sc_name}")
        func_name = raw_func_name
        counter = 2
        while func_name in used_func_names:
            func_name = f"{raw_func_name}_{counter}"
            counter += 1
        used_func_names.add(func_name)

        lines.append("")
        lines.append("")
        lines.append("# " + "=" * 75)
        lines.append(f"# Scenario {idx + 1}: {sc_name} [{sc_id}]")
        lines.append("# " + "=" * 75)
        lines.append("@pytest.mark.asyncio")
        lines.append(f"async def {func_name}():")
        lines.append('    """')
        lines.append(f"    Scenario ID: {sc_id}")
        lines.append(f"    Name: {sc_name}")
        if sc_desc:
            lines.append(f"    Description: {sc_desc}")
        lines.append(f"    Steps: {len(all_steps)}")
        lines.append('    """')
        lines.append("    context: Dict[str, Any] = {}")
        lines.append("    base_prefix = urlparse(BASE_URL).path.rstrip('/')")
        lines.append("")
        lines.append("    async def rewrite_redirect(response: httpx.Response):")
        lines.append("        if response.is_redirect and 'location' in response.headers:")
        lines.append("            loc = response.headers['location']")
        lines.append("            if base_prefix and loc.startswith('/') and not loc.startswith(base_prefix + '/') and loc != base_prefix:")
        lines.append("                response.headers['location'] = f'{base_prefix}{loc}'")
        lines.append("")
        lines.append("    async with httpx.AsyncClient(")
        lines.append("        base_url=BASE_URL,")
        lines.append("        follow_redirects=True,")
        lines.append("        event_hooks={'response': [rewrite_redirect]},")
        lines.append("    ) as client:")

        for st_idx, st in enumerate(all_steps):
            st_id = st.get("step_id", f"step_{st_idx + 1}")
            method = st.get("method", "GET").upper()
            path_tmpl = st.get("path_template", "/")
            path_params = st.get("path_params", {})
            query_params = st.get("query_params", {})
            headers = st.get("headers", {})
            body = st.get("request_body")
            expected_status = st.get("expected_status", 200)
            captures = st.get("captures", [])
            assertions = st.get("semantic_assertions", [])
            timeout = st.get("timeout_seconds", 10.0)

            lines.append("")
            lines.append("        # -------------------------------------------------------------------")
            lines.append(f"        # Step {st_idx + 1}: {st_id} ({method} {path_tmpl})")
            lines.append("        # -------------------------------------------------------------------")
            if st_idx > 0:
                lines.append("        if STEP_DELAY_SECONDS > 0:")
                lines.append("            await asyncio.sleep(STEP_DELAY_SECONDS)")

            # Path formatting
            lines.append(f"        path_{st_idx} = {repr(path_tmpl)}")
            if path_params:
                lines.append(f"        path_params_{st_idx} = {repr(path_params)}")
                lines.append(f"        for pk, pv in path_params_{st_idx}.items():")
                lines.append("            pv_clean = str(pv).strip('{}$')")
                lines.append("            if pv_clean in context:")
                lines.append("                pv = context[pv_clean]")
                lines.append("            elif str(pv).startswith('{{') and str(pv).endswith('}}'):")
                lines.append("                pv = '1' if 'id' in pv_clean.lower() else f'sample_{pv_clean}'")
                lines.append(f"            path_{st_idx} = path_{st_idx}.replace('{{' + pk + '}}', str(pv))")
            lines.append(f"        path_{st_idx} = resolve_variables(path_{st_idx}, context)")

            # Query params
            if query_params:
                lines.append(f"        params_{st_idx} = resolve_deep({repr(query_params)}, context)")
            else:
                lines.append(f"        params_{st_idx} = None")

            # Headers
            lines.append(f"        headers_{st_idx} = resolve_deep({repr(headers)}, context) or {{}}")
            lines.append(f'        headers_{st_idx}.setdefault("User-Agent", "OASTestAutomation/1.0 (test-automation; contact@example.com)")')

            # Body
            if body is not None:
                lines.append(f"        body_{st_idx} = resolve_deep({repr(body)}, context)")

            # Execute HTTP request
            lines.append(f"        resp_{st_idx} = await client.request(")
            lines.append(f'            method="{method}",')
            lines.append(f"            url=path_{st_idx},")
            lines.append(f"            params=params_{st_idx},")
            lines.append(f"            headers=headers_{st_idx},")
            if body is not None:
                lines.append(f"            json=body_{st_idx},")
            lines.append(f"            timeout={timeout},")
            lines.append("        )")
            if 200 <= expected_status < 300:
                lines.append(f"        if resp_{st_idx}.status_code == 404 and context:")
                lines.append("            await asyncio.sleep(max(STEP_DELAY_SECONDS, 0.35))")
                lines.append(f"            resp_{st_idx} = await client.request(")
                lines.append(f'                method="{method}",')
                lines.append(f"                url=path_{st_idx},")
                lines.append(f"                params=params_{st_idx},")
                lines.append(f"                headers=headers_{st_idx},")
                if body is not None:
                    lines.append(f"                json=body_{st_idx},")
                lines.append(f"                timeout={timeout},")
                lines.append("            )")

            # Status assertion
            lines.append(f"        assert resp_{st_idx}.status_code == {expected_status}, (")
            lines.append(f"            f\"Step '{st_id}' failed: Expected HTTP {expected_status}, \"")
            lines.append(f"            f\"got {{resp_{st_idx}.status_code}}. Response: {{resp_{st_idx}.text}}\"")
            lines.append("        )")

            # Parse JSON
            if captures or assertions:
                lines.append(f"        resp_json_{st_idx} = resp_{st_idx}.json() if 'json' in resp_{st_idx}.headers.get('content-type', '').lower() else {{}}")

            # Captures
            for cap in captures:
                var_name = cap.get("variable_name")
                json_path = cap.get("json_path")
                if var_name and json_path:
                    lines.append(f"        val_{st_idx} = extract_jsonpath(resp_json_{st_idx}, {repr(json_path)})")
                    lines.append(f"        if val_{st_idx} is not None:")
                    lines.append(f"            context[{repr(var_name)}] = val_{st_idx}")

            # Semantic assertions
            for ass in assertions:
                expr = ass.get("target_expression", "$")
                op = ass.get("operator", "EQUALS")
                exp_v = ass.get("expected_value")

                lines.append(f"        actual_val = extract_jsonpath(resp_json_{st_idx}, {repr(expr)})")
                if exp_v is not None:
                    lines.append(f"        exp_val = resolve_variables(str({repr(exp_v)}), context)")

                if op == "EQUALS":
                    lines.append("        assert are_values_equivalent(actual_val, exp_val), (")
                    lines.append(f"            f\"Step '{st_id}' semantic assertion failed: Expected {{actual_val}} == {{exp_val}}\"")
                    lines.append("        )")
                elif op == "NOT_EQUALS":
                    lines.append("        assert not are_values_equivalent(actual_val, exp_val), (")
                    lines.append(f"            f\"Step '{st_id}' semantic assertion failed: Expected {{actual_val}} != {{exp_val}}\"")
                    lines.append("        )")
                elif op == "CONTAINS":
                    lines.append("        assert actual_val is not None and str(exp_val).lower() in str(actual_val).lower(), (")
                    lines.append(f"            f\"Step '{st_id}' semantic assertion failed: Expected {{actual_val}} to contain {{exp_val}}\"")
                    lines.append("        )")
                elif op == "GREATER_THAN":
                    lines.append("        assert actual_val is not None and float(actual_val) > float(exp_val), (")
                    lines.append(f"            f\"Step '{st_id}' semantic assertion failed: Expected {{actual_val}} > {{exp_val}}\"")
                    lines.append("        )")
                elif op == "LESS_THAN":
                    lines.append("        assert actual_val is not None and float(actual_val) < float(exp_val), (")
                    lines.append(f"            f\"Step '{st_id}' semantic assertion failed: Expected {{actual_val}} < {{exp_val}}\"")
                    lines.append("        )")
                elif op == "MATCHES_REGEX":
                    lines.append("        assert actual_val is not None and bool(re.search(str(exp_val), str(actual_val))), (")
                    lines.append(f"            f\"Step '{st_id}' semantic assertion failed: Expected {{actual_val}} to match {{exp_val}}\"")
                    lines.append("        )")
                elif op == "NOT_NULL":
                    safe_expr = expr.replace('"', "").replace("'", "")
                    lines.append("        assert actual_val is not None, (")
                    lines.append(f"            \"Step '{st_id}' semantic assertion failed: Expected {safe_expr} to be NOT NULL\"")
                    lines.append("        )")

    lines.append("")
    lines.append("")
    lines.append('if __name__ == "__main__":')
    lines.append("    import sys")
    lines.append('    sys.exit(pytest.main(["-v", __file__]))')
    lines.append("")

    return "\n".join(lines)
