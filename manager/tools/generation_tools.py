def render_test_code_from_plan(plan: TestPlan) -> str:
    """Renders PyTest suite code from a validated TestPlan as a string."""
    template = Template(PYTEST_SUITE_TEMPLATE)
    return template.render(plan=plan)


def write_test_file_from_plan(
    session_id: str, plan: TestPlan, output_dir: str = None
) -> str:
    """Renders and writes a PyTest file from a validated TestPlan."""
    logger.info(
        "[%s] Rendering test suite for API: '%s'...", session_id, plan.api_title
    )

    rendered_code = render_test_code_from_plan(plan)

    if output_dir:
        out_dir = output_dir
    else:
        repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
        out_dir = os.path.join(repo_root, "session_workspaces", session_id, "tests")

    os.makedirs(out_dir, exist_ok=True)

    safe_title = re.sub(r"[^a-zA-Z0-9_]", "_", plan.api_title).lower()
    file_path = os.path.join(out_dir, f"test_{safe_title}.py")

    with open(file_path, "w", encoding="utf-8") as f:
        f.write(rendered_code)

    logger.info(
        "[%s] Test suite written to %s (%d test cases).",
        session_id,
        file_path,
        len(plan.tests),
    )
    return file_path
