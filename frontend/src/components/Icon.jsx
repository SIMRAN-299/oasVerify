export function Icon({ name, className = '', size, strokeWidth = 2, style }) {
  const cls = `icon ${className}`.trim()
  const sizeStyle = size ? { width: size, height: size, ...style } : style
  if (FILLED_ICONS[name]) {
    const { viewBox, path } = FILLED_ICONS[name]
    return (
      <svg className={cls} viewBox={viewBox} fill="currentColor" aria-hidden="true" style={sizeStyle}>
        {path}
      </svg>
    )
  }
  const paths = STROKE_ICONS[name] || STROKE_ICONS.info
  return (
    <svg
      className={cls}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      style={sizeStyle}
    >
      {paths}
    </svg>
  )
}

/**
 * Status indicator used by journey and step rows.
 * Accepts: idle | running | healing | passed | failed | skipped (plus legacy pass/fail).
 */
export function StatusIcon({ state, size = 18, label }) {
  const normalized =
    state === 'pass' ? 'passed' : state === 'fail' ? 'failed' : state || 'idle'

  let iconName = null
  if (normalized === 'running' || normalized === 'healing') iconName = 'loader'
  else if (normalized === 'passed') iconName = 'check-circle'
  else if (normalized === 'failed') iconName = 'x-circle'
  else if (normalized === 'skipped') iconName = 'minus-circle-filled'

  const ariaLabel =
    label ||
    (normalized === 'idle'
      ? 'Not run'
      : normalized === 'running'
      ? 'Running'
      : normalized === 'healing'
      ? 'Self-healing'
      : normalized === 'passed'
      ? 'Passed'
      : normalized === 'failed'
      ? 'Failed'
      : 'Skipped')

  return (
    <span
      className="status-icon"
      data-state={normalized}
      role="img"
      aria-label={ariaLabel}
      style={{ width: size + 2, height: size + 2 }}
    >
      {iconName && <Icon name={iconName} size={size} />}
    </span>
  )
}
